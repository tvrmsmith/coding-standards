/**
 * Guideline **"Comments"** (coding-standards/SKILL.md): code documents itself, and knowledge
 * another agent needs lives in a test. Its C# half is the `NoCommentsAnalyzer` Roslyn analyzer
 * (TVRM0008) and its Go half is the `tvrmsmith-no-comments` golangci-lint module plugin.
 *
 * Every comment is reported except four kinds, each of which is read by a tool or carries a
 * public contract rather than narrating the code:
 *
 * - a doc comment, `/** ... *\/`, the JSDoc and TSDoc form, sitting above a declaration. One
 *   above a statement documents nothing, so it is reported like any other comment, which keeps
 *   the exemption from being the easy way around the rule
 * - a directive or suppression a tool reads: ESLint and TypeScript directives, triple-slash
 *   references, coverage and formatter ignores, JSX pragmas and pure annotations
 * - a shebang
 * - any comment in a generated file, recognised by a marker in the comments above its first
 *   token
 */

/**
 * The opening words of a comment a tool reads, matched against the comment's text with its
 * delimiters stripped, and the comment forms the tool honours it in.
 *
 * Each entry is a family rather than one spelling, so `eslint-disable-next-line` and
 * `eslint-disable-line` are covered by the `eslint-disable` prefix. ESLint reads its inline
 * configuration, `global` and `exported` directives only from block comments, so a line comment
 * opening with the same word is prose and stays reported.
 */
const DIRECTIVES = [
  { pattern: /^eslint-(disable|enable)\b/, forms: ['Line', 'Block'] },
  { pattern: /^(eslint|eslint-env|globals?|exported)\s/, forms: ['Block'] },
  { pattern: /^@ts-(ignore|expect-error|nocheck|check)\b/, forms: ['Line', 'Block'] },
  { pattern: /^<(reference|amd-module|amd-dependency)\b/, forms: ['TripleSlash'] },
  { pattern: /^(istanbul|c8|v8)\s+ignore\b/, forms: ['Line', 'Block'] },
  { pattern: /^prettier-ignore\b/, forms: ['Line', 'Block'] },
  { pattern: /^@jsx(ImportSource|Frag|Runtime)?\s/, forms: ['Block'] },
  { pattern: /^[#@]__(PURE|NO_SIDE_EFFECTS)__$/, forms: ['Block'] },
]

/** Markers the common code generators write into a file's header. */
const GENERATED_MARKER = /@generated\b|\bDO NOT EDIT\b|<auto-generated|\bauto-?generated\b/i

/** A triple-slash directive is a line comment whose text opens with a third slash. */
function formOf(comment) {
  return comment.type === 'Line' && comment.value.startsWith('/') ? 'TripleSlash' : comment.type
}

/** The comment's text without its delimiters or a triple-slash's third slash. */
function bodyOf(comment) {
  return (formOf(comment) === 'TripleSlash' ? comment.value.slice(1) : comment.value).trim()
}

/**
 * The nodes a doc comment can document. A doc comment on anything else, an `if` or a call, is
 * prose in doc-comment delimiters. An import is on the list because a file overview, `@file` or
 * `@module`, sits above the imports.
 */
const DECLARATIONS = new Set([
  'ImportDeclaration',
  'FunctionDeclaration',
  'ClassDeclaration',
  'VariableDeclaration',
  'ExportNamedDeclaration',
  'ExportDefaultDeclaration',
  'ExportAllDeclaration',
  'MethodDefinition',
  'PropertyDefinition',
  'AccessorProperty',
  'Property',
  'TSAbstractMethodDefinition',
  'TSAbstractPropertyDefinition',
  'TSAbstractAccessorProperty',
  'TSDeclareFunction',
  'TSInterfaceDeclaration',
  'TSTypeAliasDeclaration',
  'TSEnumDeclaration',
  'TSEnumMember',
  'TSModuleDeclaration',
  'TSPropertySignature',
  'TSMethodSignature',
  'TSIndexSignature',
  'TSCallSignatureDeclaration',
  'TSConstructSignatureDeclaration',
])

/** Whether the comment is written as a doc comment: `/** ... *\/` in JS and TS. */
function isDocCommentSyntax(comment) {
  return comment.type === 'Block' && comment.value.startsWith('*') && comment.value !== '*'
}

/**
 * Where a declaration's own text begins: its first decorator when it has one, since the parser
 * starts a decorated class's range after its decorators.
 */
function declarationStart(node) {
  return (node.decorators?.[0] ?? node).range[0]
}

/**
 * Whether the comment documents a declaration: written as a doc comment, with the next token
 * being where a declaration begins.
 */
function isDocComment(sourceCode, declarationStarts, comment) {
  if (!isDocCommentSyntax(comment)) return false
  const next = sourceCode.getTokenAfter(comment)
  return next !== null && declarationStarts.has(next.range[0])
}

/** Whether a tool reads the comment, so deleting it would change what a tool does. */
function isDirective(comment) {
  const form = formOf(comment)
  const body = bodyOf(comment)
  return DIRECTIVES.some(({ pattern, forms }) => forms.includes(form) && pattern.test(body))
}

/** Whether a comment above the file's first token marks the whole file as generated. */
function isGeneratedFile(sourceCode) {
  const firstToken = sourceCode.ast.tokens[0]
  return sourceCode
    .getAllComments()
    .filter((comment) => !firstToken || comment.range[1] <= firstToken.range[0])
    .some((comment) => GENERATED_MARKER.test(comment.value))
}

function isExempt(sourceCode, declarationStarts, comment) {
  return (
    comment.type === 'Shebang' ||
    isDirective(comment) ||
    isDocComment(sourceCode, declarationStarts, comment)
  )
}

/** @type {import('eslint').Rule.RuleModule} */
const rule = {
  meta: {
    type: 'suggestion',
    docs: {
      description:
        'Disallow code comments other than doc comments, tool directives and suppressions, and comments in generated files',
      recommended: true,
      url: 'https://github.com/tvrmsmith/coding-standards/blob/main/packages/eslint-plugin-tvrmsmith/docs/rules/no-comments.md',
    },
    schema: [],
    messages: {
      noComments:
        'Remove this comment. Code should document itself: carry the meaning in a name, a type or an extracted function. A comment is often there to justify a workaround, and the fix for a workaround is the code. If another agent needs to know this, write a test that documents the behavior instead. Doc comments, suppressions, tool directives and generated files are exempt.',
    },
  },

  create(context) {
    const { sourceCode } = context
    const declarationStarts = new Set()
    const recordDeclaration = (node) => {
      declarationStarts.add(declarationStart(node))
    }

    return {
      ...Object.fromEntries([...DECLARATIONS].map((type) => [type, recordDeclaration])),

      'Program:exit'() {
        if (isGeneratedFile(sourceCode)) return

        for (const comment of sourceCode.getAllComments()) {
          if (isExempt(sourceCode, declarationStarts, comment)) continue
          context.report({ loc: comment.loc, messageId: 'noComments' })
        }
      },
    }
  },
}

export default rule
