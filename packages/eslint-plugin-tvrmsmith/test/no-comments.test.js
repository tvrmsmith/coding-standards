import { describe, it } from 'node:test'

import tsParser from '@typescript-eslint/parser'
import { RuleTester } from 'eslint'

import rule from '../rules/no-comments.js'

globalThis.describe = describe
globalThis.it = it

const ruleTester = new RuleTester({
  languageOptions: {
    parser: tsParser,
    ecmaVersion: 2022,
    sourceType: 'module',
    parserOptions: { ecmaFeatures: { jsx: true } },
  },
})

const reported = { messageId: 'noComments' }

ruleTester.run('no-comments', rule, {
  valid: [
    { name: 'no comments at all', code: 'const a = 1' },

    { name: 'a JSDoc comment on a function', code: '/** Adds one. */\nexport function inc(n: number) { return n + 1 }' },
    { name: 'a TSDoc comment on an interface member', code: 'interface User {\n  /** In whole years. */\n  age: number\n}' },
    { name: 'a doc comment on a class method', code: 'class A {\n  /** Resets the cache. */\n  reset() {}\n}' },
    { name: 'a doc comment on an object literal property', code: 'const config = {\n  /** Milliseconds. */\n  timeout: 30\n}' },
    { name: 'a doc comment on a nested local', code: 'function f() {\n  /** Seconds. */\n  const ttl = 5\n  return ttl\n}' },
    { name: 'a doc comment on a type alias', code: '/** A user id. */\ntype Id = string' },
    { name: 'a doc comment on an enum member', code: 'enum Mode {\n  /** Never retries. */\n  Once,\n}' },
    { name: 'a doc comment on a decorated class', code: '/** The app shell. */\n@Component()\nexport class Shell {}' },
    { name: 'a file overview doc comment above the imports', code: "/** @file The HTTP client. */\nimport x from 'x'\nexport default x" },

    { name: 'eslint-disable-next-line with a reason', code: '// eslint-disable-next-line no-console -- the CLI prints\nconsole.log(1)' },
    { name: 'eslint-disable-line as a trailing comment', code: 'console.log(1) // eslint-disable-line no-console' },
    { name: 'an eslint-disable block', code: '/* eslint-disable no-console */\nconsole.log(1)\n/* eslint-enable no-console */' },
    { name: 'an inline eslint config comment', code: '/* eslint eqeqeq: "off" */\nconst a = 1' },
    { name: 'a global directive', code: '/* global window */\nwindow.x = 1' },
    { name: '@ts-expect-error', code: '// @ts-expect-error the fixture is deliberately wrong\nconst a: number = "x"' },
    { name: '@ts-ignore', code: '// @ts-ignore\nconst a: number = "x"' },
    { name: '@ts-nocheck', code: '// @ts-nocheck\nconst a = 1' },
    { name: 'a triple-slash reference', code: '/// <reference types="vite/client" />\nconst a = 1' },
    { name: 'an istanbul ignore', code: '/* istanbul ignore next */\nconst a = 1' },
    { name: 'a c8 ignore', code: '/* c8 ignore next */\nconst a = 1' },
    { name: 'a v8 ignore', code: '/* v8 ignore next */\nconst a = 1' },
    { name: 'prettier-ignore', code: '// prettier-ignore\nconst matrix = [1,0,0,1]' },
    { name: 'a JSX import source pragma', code: "/* @jsxImportSource preact */\nexport const a = <div />" },
    { name: 'a pure annotation', code: 'export const a = /* #__PURE__ */ make()' },
    { name: 'a shebang', code: '#!/usr/bin/env node\nconst a = 1' },

    { name: 'a file marked @generated', code: '// @generated by protoc\n// tells why the field is optional\nconst a = 1' },
    { name: 'a file marked DO NOT EDIT', code: '// Code generated by sqlc. DO NOT EDIT.\n\n// query helpers\nconst a = 1' },
    { name: 'a file marked auto-generated', code: '/* This file is auto-generated. */\nconst a = 1 // trailing' },
  ],

  invalid: [
    { name: 'an own-line line comment', code: '// increment a\nlet a = 1\na++', errors: [reported] },
    { name: 'a trailing comment', code: 'let a = 1 // why', errors: [reported] },
    { name: 'a block comment', code: '/* the retry is inlined because the helper is not ready */\nconst a = 1', errors: [reported] },
    { name: 'commented-out code', code: '// const b = 2\nconst a = 1', errors: [reported] },
    { name: 'a TODO', code: '// TODO: remove once the API is fixed\nconst a = 1', errors: [reported] },
    { name: 'each line of a run is reported', code: '// one\n// two\nconst a = 1', errors: [reported, reported] },
    { name: 'a comment inside a function body', code: 'function f() {\n  // workaround for the flaky clock\n  return 1\n}', errors: [reported] },
    { name: 'a JSX comment', code: 'export const a = <div>{/* hidden for now */}</div>', errors: [reported] },
    { name: 'a doc comment above a statement documents nothing', code: 'function f(x: number) {\n  /** The API rounds down, so add one. */\n  if (x) return x + 1\n  return 0\n}', errors: [reported] },
    { name: 'a doc comment above an expression statement', code: '/** Kick the cache before startup. */\nwarm()', errors: [reported] },
    { name: 'a doc comment at the end of the file', code: 'const a = 1\n/** trailing prose */', errors: [reported] },
    { name: 'an empty block comment', code: '/**/\nconst a = 1', errors: [reported] },
    { name: 'a line comment opening with eslint is prose', code: '// eslint complains here so the check is inlined\nconst a = 1', errors: [reported] },
    { name: 'a line comment opening with global is prose', code: '// global state is reset in the test setup\nconst a = 1', errors: [reported] },
    { name: 'a generated marker below the first token does not exempt the file', code: 'const a = 1\n// @generated\n// prose', errors: [reported, reported] },
    { name: 'a licence header is still a comment', code: '// Copyright 2026 Example Corp.\nconst a = 1', errors: [reported] },
  ],
})
