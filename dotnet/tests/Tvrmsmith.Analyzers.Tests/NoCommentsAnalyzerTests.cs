using System.Threading;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;
using Xunit;

namespace Tvrmsmith.Analyzers.Tests;

/// <summary>TVRM0008 <c>no-comments</c>.</summary>
/// <remarks>
/// Sources mark each comment that must be reported with <c>[|...|]</c>, so a test reads as the
/// file it describes and the expected spans need no line and column arithmetic.
/// </remarks>
public class NoCommentsAnalyzerTests
{
    private static Task Run(string source, DocumentationMode mode = DocumentationMode.Diagnose)
    {
        var test = new Test(mode) { TestCode = source };
        return test.RunAsync(CancellationToken.None);
    }

    private static Task RunGenerated(string fileName, string source)
    {
        var test = new Test(DocumentationMode.Diagnose);
        test.TestState.Sources.Add((fileName, source));
        return test.RunAsync(CancellationToken.None);
    }

    [Fact]
    public Task SilentOnNoCommentsAtAll() => Run("class C { }");

    [Fact]
    public Task SilentOnAnXmlDocCommentOnAType() =>
        Run("""
            /// <summary>A user.</summary>
            class User { }
            """);

    [Fact]
    public Task SilentOnXmlDocCommentsOnMembers() =>
        Run("""
            /// <summary>A user.</summary>
            class User
            {
                /// <summary>In whole years.</summary>
                public int Age { get; set; }

                /// <summary>Resets the user.</summary>
                [System.Obsolete]
                public void Reset() { }

                /// <summary>The user's id.</summary>
                private readonly int _id;
            }
            """);

    [Fact]
    public Task SilentOnAMultiLineDocComment() =>
        Run("""
            /** <summary>A user.</summary> */
            class User { }
            """);

    [Fact]
    public Task SilentOnAnEnumMemberDocComment() =>
        Run("""
            /// <summary>Retry modes.</summary>
            enum Mode
            {
                /// <summary>Never retries.</summary>
                Once,
            }
            """);

    [Fact]
    public Task SilentOnALocalFunctionDocComment() =>
        Run("""
            /// <summary>Holds a local function.</summary>
            class C
            {
                /// <summary>Runs.</summary>
                void M()
                {
                    /// <summary>Adds one.</summary>
                    int Inc(int n) => n + 1;
                    Inc(1);
                }
            }
            """);

    /// <summary>
    /// A project that does not generate a documentation file parses with
    /// <see cref="DocumentationMode.None"/>, where <c>///</c> arrives as a plain comment.
    /// </summary>
    [Fact]
    public Task SilentOnADocCommentWhenDocumentationIsNotParsed() =>
        Run("""
            /// <summary>A user.</summary>
            class User { }
            """,
            DocumentationMode.None);

    [Fact]
    public Task SilentOnAPragmaReason() =>
        Run("""
            /// <summary>Holds a suppression.</summary>
            class C
            {
            #pragma warning disable CS0169 // the field is read through reflection
                private int _unused;
            #pragma warning restore CS0169
            }
            """);

    [Fact]
    public Task SilentOnAReSharperSuppression() =>
        Run("""
            // ReSharper disable once UnusedMember.Global
            /// <summary>Holds a suppression.</summary>
            class C { }
            """);

    [Fact]
    public Task SilentOnNoSonar() => Run("class C { int _a; } // NOSONAR");

    [Fact]
    public Task SilentOnAFormatterToggle() =>
        Run("""
            // @formatter:off
            class C { }
            // @formatter:on
            """);

    [Fact]
    public Task SilentInAFileMarkedAutoGenerated() =>
        RunGenerated("Client.cs", """
            // <auto-generated/>
            class C
            {
                // narrated by the generator
                int _a;
            }
            """);

    [Fact]
    public Task SilentInAGeneratedFileByName() =>
        RunGenerated("Client.g.cs", """
            class C
            {
                // narrated by the generator
                int _a;
            }
            """);

    [Fact]
    public Task ReportsAnOwnLineComment() =>
        Run("""
            [|// a user|]
            class User { }
            """);

    [Fact]
    public Task ReportsATrailingComment() => Run("class C { int _a; [|// why|]\n}");

    [Fact]
    public Task ReportsABlockComment() =>
        Run("""
            [|/* the retry is inlined because the helper is not ready */|]
            class C { }
            """);

    [Fact]
    public Task ReportsEachLineOfARun() =>
        Run("""
            [|// one|]
            [|// two|]
            class C { }
            """);

    [Fact]
    public Task ReportsACommentInsideAMethodBody() =>
        Run("""
            /// <summary>Holds a method.</summary>
            class C
            {
                /// <summary>Runs.</summary>
                int M()
                {
                    [|// workaround for the flaky clock|]
                    return 1;
                }
            }
            """);

    [Fact]
    public Task ReportsCommentedOutCode() =>
        Run("""
            [|// var b = 2;|]
            class C { }
            """);

    /// <summary>
    /// A doc comment above a statement documents nothing, so it is prose in doc-comment
    /// delimiters and is reported. The compiler's own CS1587 says the same about it.
    /// </summary>
    [Fact]
    public Task ReportsADocCommentAboveAStatement() =>
        Run("""
            /// <summary>Holds a method.</summary>
            class C
            {
                /// <summary>Runs.</summary>
                int M(int x)
                {
                    [|/// The API rounds down, so add one.|]
                    return x + 1;
                }
            }
            """,
            DocumentationMode.Parse);

    [Fact]
    public Task ReportsADocCommentAboveAStatementWhenDocumentationIsNotParsed() =>
        Run("""
            /// <summary>Holds a method.</summary>
            class C
            {
                /// <summary>Runs.</summary>
                int M(int x)
                {
                    [|/// The API rounds down, so add one.|]
                    return x + 1;
                }
            }
            """,
            DocumentationMode.None);

    [Fact]
    public Task ReportsAnEmptyBlockComment() =>
        Run("""
            [|/**/|]
            class C { }
            """);

    [Fact]
    public Task ReportsALicenceHeader() =>
        Run("""
            [|// Copyright 2026 Example Corp.|]
            class C { }
            """);

    private sealed class Test : CSharpAnalyzerTest<NoCommentsAnalyzer, DefaultVerifier>
    {
        public Test(DocumentationMode mode)
        {
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80;
            SolutionTransforms.Add((solution, projectId) =>
                solution.WithProjectParseOptions(
                    projectId,
                    ((CSharpParseOptions)solution.GetProject(projectId)!.ParseOptions!).WithDocumentationMode(mode)));
        }
    }
}
